"""# Model-Based Reflex Agent"""

model = {'A': 'Unknown',  'B': 'Unknown'}

def model_based_reflex_agent(percept):
    global model
    location = percept[0]
    condition = percept[1]

    if condition != 'Unknown' and  model[location] != 'Reported':
        model[location] =  condition

    if model['A'] in ['Safe', 'Reported'] and  model['B'] in ['Safe', 'Reported']:
        action = 'EndPatrol'
    elif condition == 'Unknown':
        action =  'Scan'
    elif model[location] == 'Intrusion':
        action = 'RaiseAlarm'
    elif location == 'A':
        action = 'MoveToB'
    elif location == 'B':
        action = 'MoveToA'
    else:
        action =  'Wait'

    if action ==  'RaiseAlarm':
        model[location] =  'Reported'

    return action

